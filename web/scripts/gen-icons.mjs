// Generates src/lib/icons.ts with only the Lucide icons the UI uses, so nothing is
// fetched from the Iconify API at runtime (strict CSP, self-hosted everything).
// Add a name to NAMES and run `npm run icons`.
import { readFileSync, writeFileSync } from 'node:fs'
import { fileURLToPath } from 'node:url'

const NAMES = [
  'layout-dashboard', 'inbox', 'wrench', 'server', 'radar', 'radio-tower', 'bell', 'folder',
  'log-out', 'user', 'copy', 'check', 'x', 'chevron-left', 'chevron-right', 'chevron-down',
  'search', 'plus', 'pencil', 'trash-2', 'archive', 'archive-restore', 'rotate-ccw', 'eye',
  'shield-check', 'ban', 'triangle-alert', 'flame', 'external-link', 'git-branch', 'container',
  'network', 'globe', 'database', 'clock', 'refresh-cw', 'send', 'key-round', 'circle-check',
  'circle-x', 'circle-alert', 'loader-circle', 'menu', 'calendar', 'tag', 'info', 'arrow-right',
  'list-checks', 'package', 'terminal', 'compass', 'moon',
]

const set = JSON.parse(
  readFileSync(fileURLToPath(new URL('../node_modules/@iconify-json/lucide/icons.json', import.meta.url)), 'utf8'),
)
const out = {}
for (const name of NAMES) {
  const real = set.icons[name] ? name : set.aliases?.[name]?.parent
  const icon = real && set.icons[real]
  if (!icon) throw new Error(`lucide icon not found: ${name}`)
  out[name] = icon.body
}
const ts = `// Generated by scripts/gen-icons.mjs — do not edit by hand.
// Lucide icons (ISC licence), 24x24 viewBox.
export const icons = ${JSON.stringify(out, null, 2)} as const

export type IconName = keyof typeof icons
`
writeFileSync(fileURLToPath(new URL('../src/lib/icons.ts', import.meta.url)), ts)
console.log(`wrote ${NAMES.length} icons`)
